def list_styles() -> list[str]:
    """Имена всех стилей."""
    return list(STYLES)


def get_style(name: str) -> dict[str, Any]:
    """Стиль по имени; при неизвестном имени — понятная ошибка со списком."""
    if name in STYLES:
        return STYLES[name]
    raise KeyError(f"нет стиля {name!r}. Доступные: {', '.join(STYLES)}")


def recipe_text(name: str) -> str:
    """Рецепт стиля в виде текста — это читает художник перед работой."""
    s = get_style(name)
    lines = [f"Стиль: {name} — {s['title']}",
             f"Размер: {s['size'][0]}x{s['size'][1]}",
             f"Палитра: {s['palette'] if isinstance(s['palette'], str) else 'своя'}",
             f"Суть: {s['summary']}", "", "Шаги:"]
    lines += [f"  {i+1}. {step}" for i, step in enumerate(s["recipe"])]
    lines += ["", f"Избегать: {s['avoid']}"]
    return "\n".join(lines)


def all_recipes() -> str:
    """Все рецепты одним текстом — для системного промпта художника."""
    return "\n\n".join(recipe_text(k) for k in STYLES)
